/**
 * Complete forensic narrative document
 */
data class ForensicNarrative(
    val version: String,
    val generatedAt: Instant,
    val evidenceId: String,
    val sessionId: String,
    val sections: List<NarrativeSection>,
    val fullText: String
)

/**
 * Individual narrative section
 */
data class NarrativeSection(
    val title: String,
    val sectionType: SectionType,
    val content: String,
    val aiInstructions: String,
    val metadata: Map<String, String>
) {
    fun toFormattedString(): String {
        return """
            |========================================================================
            |$title
            |========================================================================
            |
            |$content
            |
            |[AI INSTRUCTION: $aiInstructions]
        """.trimMargin()
    }
}

/**
 * Section types for structured parsing
 */
enum class SectionType {
    IDENTIFICATION,
    TEMPORAL,
    JURISDICTION,
    CHAIN_OF_CUSTODY,
    CONTENT,
    CONTRADICTIONS,
    RIGHTS,
    AI_GUIDANCE,
    VERIFICATION
}

/**
 * Case context provided by user
 */
data class CaseContext(
    val caseType: String,
    val userDescription: String,
    val urgency: Urgency,
    val relatedMatters: List<String> = emptyList()
)

/**
 * Urgency levels
 */
enum class Urgency {
    LOW,
    MEDIUM,
    HIGH,
    CRITICAL
}

/**
 * Forensic finding from document analysis
 */
data class ForensicFinding(
    val type: FindingType,
    val severity: Severity,
    val description: String,
    val evidenceReference: String? = null,
    val recommendation: String? = null,
    val category: String? = null
)

/**
 * Finding types
 */
enum class FindingType {
    CONTENT_OBSERVATION,
    CONTRADICTION,
    INCONSISTENCY,
    POTENTIAL_ISSUE,
    RIGHTS_CONCERN,
    COERCION_INDICATOR,
    METADATA_MISMATCH,
    FINANCIAL_ANOMALY
}

/**
 * Severity levels
 */
enum class Severity {
    INFO,
    LOW,
    MEDIUM,
    HIGH,
    CRITICAL
}
