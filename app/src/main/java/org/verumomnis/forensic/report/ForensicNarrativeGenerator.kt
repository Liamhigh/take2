        val captureTime = evidence.captureTimestampUtc
        val localTime = evidence.getLocalCaptureTime()
        val timezone = evidence.captureTimezone
        
        return NarrativeSection(
            title = "TEMPORAL CONTEXT",
            sectionType = SectionType.TEMPORAL,
            content = """
                |TEMPORAL CONTEXT FOR LEGAL ANALYSIS
                |===================================
                |
                |Evidence Capture Timestamp:
                |  - UTC Time: ${evidence.getIsoTimestamp()}
                |  - Local Time: $localTime
                |  - Timezone: ${timezone.id}
                |
                |Date Components (for statute of limitations analysis):
                |  - Year: ${captureTime.atZone(timezone).year}
                |  - Month: ${captureTime.atZone(timezone).monthValue}
                |  - Day: ${captureTime.atZone(timezone).dayOfMonth}
                |  - Day of Week: ${captureTime.atZone(timezone).dayOfWeek}
                |
                |CRITICAL FOR LEGAL AI:
                |When providing legal advice, consider:
                |  1. Applicable statutes of limitations based on this date
                |  2. Law versions in effect on this date
                |  3. Business hours/days for procedural requirements
                |  4. Any time-sensitive filing requirements
            """.trimMargin(),
            aiInstructions = "This section provides the exact timestamp when evidence was captured. Use the UTC time for cross-jurisdictional analysis and the local time for jurisdiction-specific deadlines. Consider any time-sensitive legal requirements.",
            metadata = mapOf(
                "utc_timestamp" to evidence.getIsoTimestamp(),
                "local_time" to localTime,
                "timezone" to timezone.id
            )
        )
    }
    
