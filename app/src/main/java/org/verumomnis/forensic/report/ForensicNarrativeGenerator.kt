                |JURISDICTION DETAILS:
                |  - Country: ${location.country ?: "Unknown"}
                |  - Country Code: ${location.countryCode ?: "Unknown"}
                |  - State/Province: ${location.administrativeArea ?: "Unknown"}
                |  - City/Locality: ${location.locality ?: "Unknown"}
                |  - Full Address: ${location.fullAddress ?: "Not available"}
                |  - Timezone: ${location.timezoneId}
                |
                |JURISDICTION STRING: ${location.getJurisdictionString()}
                |
                |CRITICAL FOR LEGAL AI:
                |When providing legal advice, determine:
                |  1. PRIMARY JURISDICTION: ${location.country ?: "Unknown"} (${location.countryCode ?: "???"})
                |  2. SUB-JURISDICTION: ${location.administrativeArea ?: "Unknown"}
                |  3. LOCAL JURISDICTION: ${location.locality ?: "Unknown"}
