/**
 * Forensic Narrative Generator
 * 
 * Generates detailed, AI-readable narratives for forensic reports.
 * 
 * The narrative is designed to be:
 * 1. Comprehensive enough for any AI to provide legal advice
 * 2. Structured for machine parsing
 * 3. Human-readable for legal professionals
 * 4. Jurisdiction-aware for applicable law determination
 * 
 * Output Structure:
 * - Timeline + Facts + Contradictions + Violations + Guidance
 * - Machine and human readable format
 * - Complete evidence mapping
 */
class ForensicNarrativeGenerator {
    
    companion object {
        private const val VERSION = "1.0"
        private const val ENGINE = "Verum Omnis Constitutional Governance Layer"
    }
    
    /**
     * Generate a comprehensive forensic narrative for AI analysis
     */
    fun generateNarrative(
        evidence: ForensicEvidence,
        seal: CryptographicSeal,
        findings: List<ForensicFinding>,
        caseContext: CaseContext
    ): ForensicNarrative {
        val sections = mutableListOf<NarrativeSection>()
        
        // Section 1: Document Identification
        sections.add(generateDocumentIdentificationSection(evidence, seal))
        
        // Section 2: Temporal Context (Critical for AI legal analysis)
        sections.add(generateTemporalContextSection(evidence))
        
        // Section 3: Jurisdictional Context (Critical for applicable law)
        sections.add(generateJurisdictionalContextSection(evidence.location))
        
        // Section 4: Evidence Chain of Custody
        sections.add(generateChainOfCustodySection(evidence, seal))
        
        // Section 5: Document Content Analysis
        sections.add(generateContentAnalysisSection(evidence, findings))
        
        // Section 6: Detected Issues and Contradictions
        sections.add(generateContradictionsSection(findings))
        
        // Section 7: Rights and Compliance Analysis
        sections.add(generateRightsAnalysisSection(findings))
        
        // Section 8: AI Guidance Instructions
        sections.add(generateAIGuidanceSection(evidence, caseContext))
        
        // Section 9: Verification and Authenticity
        sections.add(generateVerificationSection(seal))
        
        return ForensicNarrative(
            version = VERSION,
            generatedAt = Instant.now(),
            evidenceId = evidence.evidenceId,
            sessionId = evidence.sessionId,
            sections = sections,
            fullText = sections.joinToString("\n\n") { it.toFormattedString() }
        )
    }
    
    private fun generateDocumentIdentificationSection(
        evidence: ForensicEvidence,
        seal: CryptographicSeal
    ): NarrativeSection {
        return NarrativeSection(
            title = "DOCUMENT IDENTIFICATION",
            sectionType = SectionType.IDENTIFICATION,
            content = """
                |FORENSIC EVIDENCE RECORD
                |========================
                |
                |This document constitutes a cryptographically sealed forensic record
                |generated by the $ENGINE.
                |
                |Evidence Identification:
                |  - Evidence ID: ${evidence.evidenceId}
                |  - Session ID: ${evidence.sessionId}
                |  - Document Type: ${evidence.documentType}
                |  - Original Filename: ${evidence.originalFilename ?: "N/A"}
                |  - Document Hash (SHA-512): ${evidence.originalHash}
                |
                |Seal Information:
                |  - Seal Algorithm: ${seal.algorithm}
                |  - Seal Version: ${seal.sealVersion}
                |  - Verification Code: ${seal.verificationCode}
                |
                |IMPORTANT FOR AI ANALYSIS:
                |This document is self-contained and cryptographically sealed. Any 
                |analysis or legal advice should consider all sections of this report.
                |The seal verification code can be used to verify document authenticity.
            """.trimMargin(),
            aiInstructions = "Use this section to identify the specific document being analyzed. The Evidence ID and Session ID provide unique identifiers for reference. The SHA-512 hash confirms document integrity.",
            metadata = mapOf(
                "evidence_id" to evidence.evidenceId,
                "session_id" to evidence.sessionId,
                "document_type" to evidence.documentType.name,
                "hash" to evidence.originalHash
            )
        )
    }
    
