    private fun generateContentAnalysisSection(
        evidence: ForensicEvidence,
        findings: List<ForensicFinding>
    ): NarrativeSection {
        val contentFindings = findings.filter { it.type == FindingType.CONTENT_OBSERVATION }
        
        return NarrativeSection(
            title = "DOCUMENT CONTENT ANALYSIS",
            sectionType = SectionType.CONTENT,
            content = """
                |DOCUMENT CONTENT ANALYSIS
                |=========================
                |
                |EXTRACTED TEXT CONTENT:
                |${evidence.extractedText.ifEmpty { "[No text content extracted]" }}
                |
                |DOCUMENT METADATA:
                |${evidence.documentMetadata.entries.joinToString("\n") { "  - ${it.key}: ${it.value}" }}
                |
                |OCR CONFIDENCE: ${(evidence.ocrConfidence * 100).toInt()}%
                |
                |CONTENT OBSERVATIONS:
                |${contentFindings.joinToString("\n") { "  - ${it.description}" }.ifEmpty { "  - No specific content observations" }}
                |
                |NOTE FOR AI ANALYSIS:
                |The extracted text above represents the machine-readable content of the
                |original document. Use this text for legal analysis, contract review,
                |or compliance checking. The OCR confidence indicates reliability.
            """.trimMargin(),
            aiInstructions = "This section contains the actual document content. Analyze the extracted text for legal implications, contractual obligations, potential issues, or compliance matters relevant to the jurisdiction identified above.",
            metadata = mapOf(
                "ocr_confidence" to evidence.ocrConfidence.toString(),
                "text_length" to evidence.extractedText.length.toString()
            )
        )
    }
    
    private fun generateContradictionsSection(findings: List<ForensicFinding>): NarrativeSection {
        val contradictions = findings.filter { 
            it.type == FindingType.CONTRADICTION || 
            it.type == FindingType.INCONSISTENCY 
        }
        val issues = findings.filter { it.type == FindingType.POTENTIAL_ISSUE }
        
        return NarrativeSection(
            title = "CONTRADICTIONS AND ISSUES",
            sectionType = SectionType.CONTRADICTIONS,
            content = """
                |DETECTED CONTRADICTIONS AND ISSUES
                |==================================
                |
                |CONTRADICTIONS DETECTED: ${contradictions.size}
                |${if (contradictions.isEmpty()) "  None detected" else contradictions.mapIndexed { i, f -> 
                    "  ${i + 1}. [${f.severity}] ${f.description}\n     Evidence: ${f.evidenceReference ?: "N/A"}"
                }.joinToString("\n")}
                |
                |POTENTIAL ISSUES: ${issues.size}
                |${if (issues.isEmpty()) "  None detected" else issues.mapIndexed { i, f -> 
                    "  ${i + 1}. [${f.severity}] ${f.description}\n     Recommendation: ${f.recommendation ?: "Review required"}"
                }.joinToString("\n")}
                |
                |CONTRADICTION ANALYSIS METHODOLOGY:
                |  The following layers were analyzed:
                |  - Timeline analysis
                |  - Statement comparison
                |  - Behavioral inconsistencies
                |  - Document metadata mismatches
                |  - Financial flows (if applicable)
                |  - Coercion indicators
                |  - Rights violations
                |  - Intent vs action mismatch
                |
                |AI GUIDANCE:
                |  Review each contradiction and issue in context of applicable law.
                |  Consider whether issues rise to level of legal concern.
            """.trimMargin(),
            aiInstructions = "This section highlights potential contradictions and issues detected in the document. Each finding should be evaluated in context of the applicable jurisdiction. Contradictions may indicate fraud, coercion, or error requiring legal attention.",
            metadata = mapOf(
                "contradiction_count" to contradictions.size.toString(),
                "issue_count" to issues.size.toString()
            )
        )
    }
    
