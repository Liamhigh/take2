    }
    
    private fun getLegalSystemDescription(countryCode: String?): String {
        return when (countryCode?.uppercase()) {
            "ZA" -> "South African law applies (mixed legal system: Roman-Dutch civil law + English common law). Constitution of South Africa is supreme."
            "US" -> "United States law applies (common law system). Federal and state laws may both apply."
            "GB", "UK" -> "United Kingdom law applies (common law system). Consider England/Wales, Scotland, or Northern Ireland specific laws."
            "AU" -> "Australian law applies (common law system). Federal and state/territory laws may both apply."
            "CA" -> "Canadian law applies (mixed: common law except Quebec which uses civil law)."
            "IN" -> "Indian law applies (common law system). Federal and state laws may both apply."
            "DE" -> "German law applies (civil law system based on codified law)."
            "FR" -> "French law applies (civil law system based on Napoleonic Code)."
            "JP" -> "Japanese law applies (civil law system with German and American influences)."
            "BR" -> "Brazilian law applies (civil law system based on codified law)."
            "NG" -> "Nigerian law applies (mixed: common law + customary law + Sharia in some states)."
            "KE" -> "Kenyan law applies (common law system with constitutional supremacy)."
            else -> "Legal system unknown. AI should research applicable legal system for country code '$countryCode'."
        }
    }
    
